using ReviewApp.Api.Enums;
using System.ComponentModel.DataAnnotations;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace ReviewApp.Api.DTOs;

/* The offline sync of the Android app (api/Sync). The device sends its queued changes ("ops") in the order the user
   made them; each one is applied on its own and answered on its own (SyncOpResult). */

public record SyncPushRequest
{
    // The user the device's queue belongs to; must be the logged-in one (409 user_mismatch otherwise)
    [Required]
    public int? UserId { get; init; }

    [Required]
    public List<SyncOpDto>? Ops { get; init; }
}

public record SyncOpDto
{
    // Generated by the device, the same on every retry of this change
    [Required]
    public Guid? OpId { get; init; }

    // One of SyncOpTypes
    [Required]
    public string? Type { get; init; }

    // Creates only: the device's temporary reference of the new review / collection, which later ops use
    // ({ "ref": ... }) before they know its real ID, in this request or a later one
    [MaxLength(DAL.Entities.SyncOperation.MaxClientRefLength)]
    public string? ClientRef { get; init; }

    // Ops that must have been applied first; if one failed, this op is skipped
    [MaxLength(50)]
    public List<Guid>? DependsOn { get; init; }

    // The op's fields, by type (Services/Sync/SyncOps.cs)
    public JsonElement Payload { get; init; }
}

public record SyncPushResponse(List<SyncOpResult> Results, List<UnlockedAchievementDto> Unlocked, DateTime ServerTime);

public static class SyncStatus
{
    // Done (also when it already was: adding an item that is there, deleting what is gone)
    public const string Applied = "applied";
    // Done after an automatic merge with changes made elsewhere (Entity shows the result)
    public const string Merged = "merged";
    // Needs the user (Reason, ConflictFields, Entity = the server's version); nothing was changed
    public const string Conflict = "conflict";
    // Permanent failure (Reason); nothing was changed
    public const string Rejected = "rejected";
    // Temporary failure (Reason); send it again later
    public const string Retry = "retry";
    // A dependency wasn't applied; send it again after that one
    public const string Skipped = "skipped";
}

public static class SyncReason
{
    // Conflicts
    public const string FieldConflict = "field_conflict";
    public const string Deleted = "deleted";
    public const string ModifiedSince = "modified_since";
    public const string AlreadyReviewed = "already_reviewed";
    public const string NameTaken = "name_taken";
    public const string CollectionDeleted = "collection_deleted";

    // Rejections
    public const string Invalid = "invalid";
    public const string UnknownType = "unknown_type";
    public const string Locked = "locked";
    public const string MediaNotFound = "media_not_found";
    public const string Self = "self";
    public const string UserNotFound = "user_not_found";
    public const string ClientRefTaken = "client_ref_taken";

    // Retries
    public const string SourceUnavailable = "source_unavailable";
    public const string Deferred = "deferred";
    public const string Busy = "busy";
    public const string ServerError = "server_error";

    // Skips
    public const string Dependency = "dependency";
}

public record SyncOpResult
{
    public Guid OpId { get; init; }
    public string Status { get; init; } = SyncStatus.Applied;

    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public string? Reason { get; init; }

    // The row the op applied to (for creates: the new one, for name_taken: the collection that has the name)
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public int? EntityId { get; init; }

    // The server's current version of it: SyncReviewDto, SyncCollectionDto or SyncProfileDto
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public JsonElement? Entity { get; init; }

    // field_conflict: the fields changed differently on both sides
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public List<string>? ConflictFields { get; init; }

    // Profile: the server values this op overwrote that differed from what the device had seen
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public Dictionary<string, string?>? Previous { get; init; }
}

/* The server's version of the user's own content, as the sync sends it (push results, changes feed).
   Times are UTC, Version is the row's rowversion (the base version of the device's next edit). */

public record SyncMediaDto
{
    public int DbMediaId { get; init; }
    public MediaType MediaType { get; init; }
    public string ExternalApiId { get; init; } = string.Empty;
    public string? Title { get; init; }
    public string? PosterUrl { get; init; }
    public DateTime? ReleaseDate { get; init; }
    public string? Creator { get; init; }
}

public record SyncReviewDto
{
    public int Id { get; init; }
    public SyncMediaDto Media { get; init; } = null!;
    public decimal Score { get; init; }
    public string? ReviewText { get; init; }
    public string? Pros { get; init; }
    public string? Cons { get; init; }
    public VisibilityLevel Visibility { get; init; }
    public DateTime CreatedAt { get; init; }
    public DateTime UpdatedAt { get; init; }
    public long Version { get; init; }
}

public record SyncCollectionItemDto
{
    public SyncMediaDto Media { get; init; } = null!;
    public int OrderIndex { get; init; }
    public DateTime AddedAt { get; init; }
}

public record SyncCollectionDto
{
    public int Id { get; init; }
    public string Name { get; init; } = string.Empty;
    public VisibilityLevel Visibility { get; init; }
    public bool IsDefault { get; init; }
    public DateTime CreatedAt { get; init; }
    public DateTime UpdatedAt { get; init; }
    public long Version { get; init; }
    public List<SyncCollectionItemDto> Items { get; init; } = [];
}

public record SyncProfileDto
{
    public string? Bio { get; init; }
    public string? ProfilePictureUrl { get; init; }
}

/* The changes feed (GET api/Sync/changes) and the visibility check (POST api/Sync/visible) */

public record SyncChangesDto
{
    // The user's own reviews and collections changed (or created) since the cursor, every visibility
    public List<SyncReviewDto> Reviews { get; init; } = [];
    public List<int> DeletedReviewIds { get; init; } = [];
    public List<SyncCollectionDto> Collections { get; init; } = [];
    public List<int> DeletedCollectionIds { get; init; } = [];

    // The next request's since; everything below it has been sent
    public long Cursor { get; init; }
    // More changes are waiting: ask again with the cursor (and continued=true) before applying the deletions of a full resync
    public bool HasMore { get; init; }
    // Everything is sent from the start: what the device has but the full run doesn't contain was deleted
    public bool FullResync { get; init; }

    // First page of a run only
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public SyncAccountDto? Account { get; init; }

    public DateTime ServerTime { get; init; }
}

// The small, frequently changing account data, sent whole on the first page of every run
public record SyncAccountDto
{
    public int UserId { get; init; }
    public string Username { get; init; } = string.Empty;
    public string? Bio { get; init; }
    public string? ProfilePictureUrl { get; init; }
    public List<UserCompactDto> Following { get; init; } = [];
    public List<UserCompactDto> Followers { get; init; } = [];
    // The newest ones (the server keeps at most 200 per user)
    public List<NotificationDto> Notifications { get; init; } = [];
    public int UnseenNotificationCount { get; init; }
}

public record SyncVisibleRequest
{
    [MaxLength(SyncVisibleLimits.MaxIds)]
    public List<int>? ReviewIds { get; init; }
    [MaxLength(SyncVisibleLimits.MaxIds)]
    public List<int>? CollectionIds { get; init; }
}

public static class SyncVisibleLimits
{
    public const int MaxIds = 1000;
}

// The asked-for IDs the user can still see; the device drops its copies of the rest
public record SyncVisibleDto(List<int> ReviewIds, List<int> CollectionIds);
